def build_demo_pdf(output_path: Path) -> Path:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    width, height = landscape(A3)
    canvas = Canvas(str(output_path), pagesize=(width, height), pageCompression=1)
    canvas.setTitle("Synthetic HVAC Specification")
    canvas.setAuthor("Spec OCR Pipeline contributors")
    canvas.setCreator("Spec OCR Pipeline demo builder")
    canvas.setSubject("Synthetic public demo with no customer data")
    canvas.setKeywords("synthetic, HVAC, specification, OCR, demo")

    canvas.setFillColor(colors.HexColor("#0F172A"))
    canvas.rect(0, height - 105, width, 105, fill=1, stroke=0)
    canvas.setFillColor(colors.white)
    canvas.setFont("Helvetica-Bold", 24)
    canvas.drawString(60, height - 48, "SYNTHETIC HVAC SPECIFICATION")
    canvas.setFont("Helvetica", 10)
    canvas.setFillColor(colors.HexColor("#CBD5E1"))
    canvas.drawString(
        60, height - 72, "Public demo - generated data only - no customer information"
    )

    table_top = 745
    header_bottom = 715
    row_height = 50
    table_bottom = header_bottom - row_height * len(ROWS)

    canvas.setFillColor(colors.HexColor("#E2E8F0"))
    canvas.rect(60, header_bottom, 1100, table_top - header_bottom, fill=1, stroke=0)
    canvas.setStrokeColor(colors.HexColor("#94A3B8"))
    canvas.setLineWidth(0.8)
    for _label, start, _end in COLUMNS:
        canvas.line(start, table_bottom, start, table_top)
    canvas.line(COLUMNS[-1][2], table_bottom, COLUMNS[-1][2], table_top)
    for index in range(len(ROWS) + 2):
        y = table_top if index == 0 else header_bottom - row_height * (index - 1)
        canvas.line(60, y, 1160, y)

    canvas.setFont("Helvetica-Bold", 8)
    canvas.setFillColor(colors.HexColor("#1E293B"))
    for label, start, _end in COLUMNS:
        canvas.drawString(start + 5, header_bottom + 10, label)

    canvas.setFont("Helvetica", 8.5)
    for row_index, values in enumerate(ROWS):
        y = header_bottom - row_height * row_index - 30
        if row_index % 2:
            canvas.setFillColor(colors.HexColor("#F8FAFC"))
            canvas.rect(60, y - 20, 1100, row_height, fill=1, stroke=0)
        canvas.setFillColor(colors.HexColor("#0F172A"))
        for value, (_label, start, _end) in zip(values, COLUMNS, strict=True):
            canvas.drawString(start + 5, y, value)

    canvas.setFillColor(colors.HexColor("#475569"))
    canvas.setFont("Helvetica", 9)
    canvas.drawString(
        60, 42, "Generated by Spec OCR Pipeline | Verify extracted quantities before use"
    )
    canvas.drawRightString(width - 30, 42, "Page 1 / 1")
    canvas.showPage()
    canvas.save()
    return output_path


def main() -> int:
    parser = argparse.ArgumentParser(description="Build the synthetic public demo PDF")
    parser.add_argument(
        "output",
        nargs="?",
        type=Path,
        default=Path("examples/demo/specification.pdf"),
    )
    args = parser.parse_args()
    print(build_demo_pdf(args.output))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
